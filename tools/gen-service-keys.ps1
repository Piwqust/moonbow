# Writes ServiceKeys.gen.h: the keys of the online services this build of Moonbow carries
# (src/net/ServiceKeys.cpp reads it). build.bat runs this before compiling.
#
# The repository holds no keys. They come from environment variables (the release workflow sets them
# from repository secrets) or, on the owner's PC, from %USERPROFILE%\.moonbow-release\service-keys.json:
#   { "opensubtitles": "...", "tmdb": "...", "lastfm": "...", "lastfmSecret": "...", "discord": "..." }
# An environment variable wins over the file. A key that is missing stays empty, and the feature then
# says that this copy of Moonbow has no key for the service.
#
# The bytes are XOR-ed with a mask so the keys are not plain strings in the exe. Anyone can still take
# them out; keys built into desktop apps are public, and the services know it (OpenSubtitles asks for
# exactly this: one key per application, never one per user).
param([Parameter(Mandatory = $true)][string]$Out)
$ErrorActionPreference = "Stop"

$keys = [ordered]@{
  OpenSubtitles = @{ Env = "MOONBOW_KEY_OPENSUBTITLES"; Json = "opensubtitles" }
  Tmdb          = @{ Env = "MOONBOW_KEY_TMDB"; Json = "tmdb" }
  LastfmKey     = @{ Env = "MOONBOW_KEY_LASTFM"; Json = "lastfm" }
  LastfmSecret  = @{ Env = "MOONBOW_KEY_LASTFM_SECRET"; Json = "lastfmSecret" }
  DiscordApp    = @{ Env = "MOONBOW_KEY_DISCORD"; Json = "discord" }
}

$local = $null
$file = Join-Path $env:USERPROFILE ".moonbow-release\service-keys.json"
if (Test-Path $file) { $local = [IO.File]::ReadAllText($file) | ConvertFrom-Json }

$sha = [Security.Cryptography.SHA256]::Create()
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("// Generated by tools/gen-service-keys.ps1 for this build. Never commit it.")
$lines.Add("#pragma once")
$lines.Add("namespace net::keys::gen {")
$have = @()
foreach ($name in $keys.Keys) {
  $value = [Environment]::GetEnvironmentVariable($keys[$name].Env)
  if (-not $value -and $local) { $value = $local.($keys[$name].Json) }
  if (-not $value) { $value = "" }
  $value = $value.Trim()
  if ($value) { $have += $name }
  $bytes = [Text.Encoding]::UTF8.GetBytes($value)
  # The mask: SHA-256 of the name, repeated. Deterministic, so the header only changes with the keys.
  $seed = $sha.ComputeHash([Text.Encoding]::UTF8.GetBytes("moonbow:$name"))
  $data = @(); $mask = @()
  for ($i = 0; $i -lt $bytes.Length; $i++) {
    $m = $seed[$i % $seed.Length] -bxor ($i * 31 -band 0xFF)
    $mask += ("0x{0:x2}" -f $m)
    $data += ("0x{0:x2}" -f ($bytes[$i] -bxor $m))
  }
  if ($bytes.Length -eq 0) { $data = @("0x00"); $mask = @("0x00") }
  $lines.Add("inline constexpr unsigned k${name}Len = $($bytes.Length);")
  $lines.Add("inline constexpr unsigned char k${name}[] = {$($data -join ',')};")
  $lines.Add("inline constexpr unsigned char k${name}Mask[] = {$($mask -join ',')};")
}
$lines.Add("}  // namespace net::keys::gen")
$text = ($lines -join "`r`n") + "`r`n"

$dir = Split-Path -Parent $Out
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
$old = if (Test-Path $Out) { [IO.File]::ReadAllText($Out) } else { "" }
if ($old -ne $text) { [IO.File]::WriteAllText($Out, $text, (New-Object System.Text.UTF8Encoding $false)) }
if ($have.Count) { Write-Host "Service keys in this build: $($have -join ', ')" }
else { Write-Host "Service keys in this build: none (see tools\gen-service-keys.ps1)" }
