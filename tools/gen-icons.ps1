# Packs design/icons/*.svg into src/gfx/IconData.inc for the Direct2D SVG renderer.
# - Figma's "inside stroke" masks become clipPaths (Direct2D SVG has no <mask>).
# - Colors are normalized to two tokens the renderer swaps at draw time:
#   #8F8F8F = primary, #AB6314 (and the orange #D37918) = secondary.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root "design\icons"
$out = Join-Path $root "src\gfx\IconData.inc"

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by tools/gen-icons.ps1 from design/icons. Do not edit by hand.")
[void]$sb.AppendLine("// clang-format off")
$count = 0
$files = [System.Collections.Generic.List[System.IO.FileInfo]](Get-ChildItem $src -Filter *.svg)
# Ordinal order: the C++ side binary-searches with std::string_view::compare.
$files.Sort([System.Comparison[System.IO.FileInfo]] { param($a, $b) [string]::CompareOrdinal($a.BaseName, $b.BaseName) })
foreach ($f in $files) {
    $svg = Get-Content $f.FullName -Raw
    $svg = [regex]::Replace($svg, '<mask id="([^"]+)"[^>]*>', '<clipPath id="$1">')
    $svg = $svg.Replace('</mask>', '</clipPath>')
    $svg = [regex]::Replace($svg, 'mask="url\(#([^)]+)\)"', 'clip-path="url(#$1)"')
    $svg = $svg -replace '(?i)#D37918', '#AB6314' -replace '(?i)#8f8f8f', '#8F8F8F' -replace '(?i)#ab6314', '#AB6314'
    $svg = ($svg -replace "\r?\n", "" -replace ">\s+<", "><").Trim()
    if ($svg.Contains(')svg"')) { throw "raw string delimiter clash in $($f.Name)" }
    [void]$sb.AppendLine("{""$($f.BaseName)"", R""svg($svg)svg""},")
    $count++
}
[IO.File]::WriteAllText($out, $sb.ToString())
"packed $count icons into $out ($([math]::Round((Get-Item $out).Length / 1KB)) KB)"
